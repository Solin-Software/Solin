_LANG_FROM_MEPS: dict[int, str] = {v: k for k, v in MEPS_FROM_LANG.items()}

JW_API_URL     = "https://b.jw-cdn.org/apis/pub-media/GETPUBMEDIALINKS"
JW_API_TIMEOUT = 8

