# Cache em memória para evitar chamadas redundantes no mesmo processo.
# Chave: (key_symbol, doc_id, track, issue_tag, meps_language)
_RESOLVE_CACHE: dict[tuple, Optional[dict]] = {}

# ── Regexes de parsing de URL ─────────────────────────────────────────────────

# Formato geral CDN: /sjjm_T_002_r720P.mp4  /osg_T_108.mp3  pub-sjjm_T_1_r720P
JW_CDN_RE = re.compile(
    r"[/\-]([A-Za-z][A-Za-z0-9]{1,11})"   # /symbol  ou  -symbol
    r"_([A-Z]{1,4})"                        # _LANG
    r"_(\d{1,4})"                           # _TRACK
    r"(?:_[^/]*)?(?:\.\w+)?$",             # sufixo de qualidade e extensão opcionais
    re.IGNORECASE,
)

# Formato pub- explícito: pub-sjjm_T_1_r720P
JW_PUB_RE = re.compile(
    r"pub-([A-Za-z0-9]+)_([A-Z]{1,4})_(\d{1,4})(?:_[^/]*)?",
    re.IGNORECASE,
)

# Formato com issue/edição: pub-w_T_202201
JW_ISSUE_RE = re.compile(
    r"pub-([A-Za-z0-9]+)_([A-Z]{1,4})_(\d{5,8})",
    re.IGNORECASE,
)

# Formato DocumentId numérico: 502100025_T_cnt_1_r720P.mp4
JW_DOCID_URL_RE = re.compile(
    r"^(\d{5,12})"               # doc_id: 5–12 dígitos
    r"_([A-Z]{1,4})"             # _LANG
    r"_[A-Za-z]+_"               # _token_ (cnt, a, b, …)
    r"(\d+)",                    # track/index
    re.IGNORECASE,
)


# ── Helpers ───────────────────────────────────────────────────────────────────

def meps_to_lang(meps_id: int, fallback: str = "E") -> str:
    """Converte ID MEPS → código de língua JW.org (ex: 5 → 'T')."""
    return _LANG_FROM_MEPS.get(meps_id, fallback)


def parse_jworg_url(url: str) -> Optional[dict]:
    """
    Tenta extrair metadados JW.org de uma URL de download.
    Retorna dict com key_symbol, track, issue_tag, doc_id, meps_language ou None.
    key_symbol pode ser None quando a mídia é identificada só por doc_id.

    Formatos suportados (exemplos reais):
      https://akamd1.jw-cdn.org/sg2/p/64dbe62/2/o/sjjm_T_002_r720P.mp4
      https://akamd1.jw-cdn.org/sg2/p/3808c4/1/o/osg_T_108.mp3
      https://download.jw.org/files/media_pub/pub-sjjm_T_1_r720P.mp4
      https://akamd1.jw-cdn.org/sg2/p/c5f721/1/o/502100025_T_cnt_1_r720P.mp4
    """
    if not url:
        return None
    url_lower = url.lower()
    if not any(d in url_lower for d in JW_DOMAINS):
        return None

    # ── Tenta formato com issue primeiro (track seria número longo) ───────
    m = JW_ISSUE_RE.search(url)
    if m:
        key_symbol = m.group(1).lower()
        lang_code  = m.group(2).upper()
        issue_tag  = int(m.group(3))
        meps       = MEPS_FROM_LANG.get(lang_code, 0)
        return {"key_symbol": key_symbol, "track": None,
                "issue_tag": issue_tag, "doc_id": None, "meps_language": meps}

    # ── Tenta formato pub-symbol_LANG_TRACK ───────────────────────────────
    m = JW_PUB_RE.search(url)
    if m:
        key_symbol = m.group(1).lower()
        lang_code  = m.group(2).upper()
        track      = int(m.group(3))
        meps       = MEPS_FROM_LANG.get(lang_code, 0)
        return {"key_symbol": key_symbol, "track": track,
                "issue_tag": None, "doc_id": None, "meps_language": meps}

    # ── Extrai basename para os formatos restantes ────────────────────────
    path_part   = url.split("?")[0]
    basename    = path_part.rsplit("/", 1)[-1]
    name_no_ext = basename.rsplit(".", 1)[0]

    # ── Formato DocumentId numérico: 502100025_T_cnt_1_r720P ─────────────
    m_doc = JW_DOCID_URL_RE.match(name_no_ext)
    if m_doc:
        doc_id_val = int(m_doc.group(1))
        lang_code  = m_doc.group(2).upper()
        track_val  = int(m_doc.group(3))
        meps       = MEPS_FROM_LANG.get(lang_code, 0)
        return {"key_symbol": None, "track": track_val,
                "issue_tag": None, "doc_id": doc_id_val, "meps_language": meps}

    # ── Formato geral: SYMBOL_LANG_TRACK[_qualidade] ─────────────────────
    m2 = re.match(
        r"^([A-Za-z][A-Za-z0-9]{1,11})_([A-Z]{1,4})_(\d{1,4})(?:_.*)?$",
        name_no_ext,
        re.IGNORECASE,
    )
    if m2:
        key_symbol = m2.group(1).lower()
        lang_code  = m2.group(2).upper()
        track      = int(m2.group(3))
        meps       = MEPS_FROM_LANG.get(lang_code, 0)
        return {"key_symbol": key_symbol, "track": track,
                "issue_tag": None, "doc_id": None, "meps_language": meps}

    return None


def resolve_jworg_meta(
    key_symbol:             Optional[str],
    doc_id:                 Optional[int],
    track:                  Optional[int],
    issue_tag:              Optional[int],
    meps_language:          int,
    fallback_lang:          str           = "E",
    major_multimedia_type:  Optional[int] = None,
) -> Optional[dict]:
    """
    Consulta a API pública JW.org e retorna metadados canônicos da mídia.
    Resultado: {"title": str | None, "duration_ticks": int | None}

    O título retornado pela API é sempre o canônico — deve sobrescrever
    qualquer título gerado automaticamente do nome de arquivo.

    Cache de processo para evitar chamadas repetidas ao mesmo item.
    Retorna None em caso de erro de rede ou mídia não encontrada.
    """
    if not key_symbol and not doc_id:
        return None

    cache_key = (key_symbol, doc_id, track, issue_tag, meps_language)
    if cache_key in _RESOLVE_CACHE:
        return _RESOLVE_CACHE[cache_key]

    is_audio   = (major_multimedia_type == 0)
    fileformat = "MP3" if is_audio else "MP4"
    lang_code  = meps_to_lang(meps_language, fallback_lang)

    params: dict[str, str] = {"langwritten": lang_code, "fileformat": fileformat}
    if key_symbol:
        params["pub"] = key_symbol
    if track is not None:
        params["track"] = str(track)
    if issue_tag:
        params["issue"] = str(issue_tag)
    if doc_id:
        params["docid"] = str(doc_id)

    api_url = f"{JW_API_URL}?{_url_parse.urlencode(params)}"
    log.debug("[jw_api] Resolving JW.org metadata: %s", api_url)

    try:
        data = get_json(api_url, timeout=JW_API_TIMEOUT, headers={"User-Agent": "Solin/1.0"})
    except HttpError as e:
        log.debug("[jw_api] JW.org API unavailable (%s/%s): %s", key_symbol, doc_id, e)
        _RESOLVE_CACHE[cache_key] = None
        return None

    result = _extract_best_meta(data, lang_code, fileformat, track)
    log.debug("[jw_api] Resolved metadata: %s", result)
    _RESOLVE_CACHE[cache_key] = result
    return result


def _extract_best_meta(
    api_response:  dict,
    lang_code:     str,
    fileformat:    str,
    target_track:  Optional[int] = None,
) -> Optional[dict]:
    """
    Navega a resposta da API JW.org e extrai {"title": str|None, "duration_ticks": int|None}.
    Prioriza entradas sem legenda que correspondam ao track pedido.
    """
    files = api_response.get("files", {})
    fmt   = fileformat.upper()

    lang_section = files.get(lang_code, {})
    entries: list = lang_section.get(fmt, [])
    if not entries:
        for section in files.values():
            if isinstance(section, dict):
                candidate = section.get(fmt, [])
                if candidate:
                    entries = candidate
                    break
    if not entries:
        return None

    _QUALITY = re.compile(r'^\d+[pP]$|^\d+kbps$', re.I)

    def _title(e: dict) -> Optional[str]:
        t = e.get("title")
        if t and isinstance(t, str) and not _QUALITY.match(t.strip()):
            return t.strip() or None
        return None

    def _dur(e: dict) -> Optional[int]:
        raw = e.get("duration") or (e.get("file") or {}).get("duration")
        try:
            return int(float(raw) * 10_000_000) if raw else None
        except (ValueError, TypeError):
            return None

    def _has_url(e: dict) -> bool:
        return bool(
            (e.get("file") or {}).get("url")
            or e.get("progressiveDownloadURL")
            or e.get("url")
        )

    def _track_matches(e: dict) -> bool:
        if target_track is None:
            return True
        raw_t = e.get("track")
        if raw_t is None:
            return True
        try:
            return int(raw_t) == target_track
        except (ValueError, TypeError):
            return True

    # Passe 1: track correto, sem legenda, com URL
    for e in entries:
        if not isinstance(e, dict) or not _has_url(e):
            continue
        if not _track_matches(e) or e.get("subtitled") is True:
            continue
        t, d = _title(e), _dur(e)
        if t or d:
            return {"title": t, "duration_ticks": d}

    # Passe 2: qualquer entrada com URL
    for e in entries:
        if isinstance(e, dict) and _has_url(e):
            return {"title": _title(e), "duration_ticks": _dur(e)}

    return None
